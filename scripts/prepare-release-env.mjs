#!/usr/bin/env node
import { randomBytes } from "node:crypto";
import { chmodSync, existsSync, mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);

if (hasFlag("--help") || hasFlag("-h")) {
  printHelp();
  process.exit(0);
}

const output = resolveFromRoot(readOption("--output") ?? ".env");
const force = hasFlag("--force");
const adminEmail = readOption("--admin-email") ?? process.env.ADMIN_EMAIL;
const baseUrl = readOption("--base-url") ?? process.env.RELEASE_BASE_URL ?? "";
const qwenApiKey = readOption("--qwen-api-key") ?? process.env.QWEN_API_KEY ?? "";
const sessionCookieSecure = resolveSecureCookie(baseUrl);
const adminPassword = readOption("--admin-password") ?? randomSecret(18);
const postgresPassword = readOption("--postgres-password") ?? randomSecret(24);
const sessionSecret = readOption("--session-secret") ?? randomSecret(48);
const httpPort = readOption("--http-port") ?? process.env.HTTP_PORT ?? "80";
const sessionMaxAgeSeconds = readOption("--session-max-age-seconds") ?? process.env.SESSION_MAX_AGE_SECONDS ?? "28800";
const postgresDb = readOption("--postgres-db") ?? process.env.POSTGRES_DB ?? "fundapp_road_fund";
const postgresUser = readOption("--postgres-user") ?? process.env.POSTGRES_USER ?? "fundapp";
const qwenBaseUrl = readOption("--qwen-base-url") ?? process.env.QWEN_BASE_URL ?? "https://token-plan.cn-beijing.maas.aliyuncs.com/compatible-mode/v1";
const qwenModel = readOption("--qwen-model") ?? process.env.QWEN_MODEL ?? "qwen3.7-max";
const releaseWriteMarker =
  readOption("--write-marker") ?? process.env.RELEASE_WRITE_MARKER ?? `phase1-${new Date().toISOString().replace(/[:.]/g, "-")}`;

const problems = validateInputs();
if (problems.length > 0) {
  console.error(`Release env generation failed:\n- ${problems.join("\n- ")}`);
  process.exit(1);
}

if (existsSync(output) && !force) {
  console.error(`${path.relative(repoRoot, output)} already exists. Pass --force to overwrite it.`);
  process.exit(1);
}

const lines = [
  "# Generated by npm run prepare:release-env. This file is intentionally gitignored.",
  "APP_AUTH_MODE=password",
  `SESSION_SECRET=${quoteEnv(sessionSecret)}`,
  `SESSION_COOKIE_SECURE=${sessionCookieSecure ? "true" : "false"}`,
  `SESSION_MAX_AGE_SECONDS=${quoteEnv(sessionMaxAgeSeconds)}`,
  `ADMIN_EMAIL=${quoteEnv(adminEmail)}`,
  `ADMIN_PASSWORD=${quoteEnv(adminPassword)}`,
  `HTTP_PORT=${quoteEnv(httpPort)}`,
  `POSTGRES_DB=${quoteEnv(postgresDb)}`,
  `POSTGRES_USER=${quoteEnv(postgresUser)}`,
  `POSTGRES_PASSWORD=${quoteEnv(postgresPassword)}`,
  "",
  "# In Compose mode the API constructs an encoded DATABASE_URL from discrete PG* variables.",
  "# Set DATABASE_URL only for direct host PostgreSQL deployments.",
  "",
  `QWEN_API_KEY=${quoteEnv(qwenApiKey)}`,
  `QWEN_BASE_URL=${quoteEnv(qwenBaseUrl)}`,
  `QWEN_MODEL=${quoteEnv(qwenModel)}`,
  ...(baseUrl ? [`RELEASE_BASE_URL=${quoteEnv(baseUrl)}`] : []),
  `RELEASE_WRITE_MARKER=${quoteEnv(releaseWriteMarker)}`,
  "",
];

mkdirSync(path.dirname(output), { recursive: true });
writeFileSync(output, `${lines.join("\n")}`, { encoding: "utf8", mode: 0o600 });
chmodSync(output, 0o600);

console.log(`Release env written: ${path.relative(repoRoot, output)}`);
console.log(`APP_AUTH_MODE=password`);
console.log(`ADMIN_EMAIL=${adminEmail}`);
console.log(`SESSION_COOKIE_SECURE=${sessionCookieSecure ? "true" : "false"}`);
console.log(`RELEASE_WRITE_MARKER=${releaseWriteMarker}`);
console.log("Generated secrets were written to the env file and were not printed.");
console.log(`Next: npm run preflight:release -- --compose --release-env-file ${path.relative(repoRoot, output)}`);

function validateInputs() {
  const errors = [];
  if (!adminEmail) {
    errors.push("pass --admin-email or set ADMIN_EMAIL");
  } else if (adminEmail === "admin@example.local" || !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(adminEmail)) {
    errors.push("ADMIN_EMAIL must be a real non-default email address");
  }

  if (sessionSecret.length < 32 || ["change-me", "dev-session-secret"].includes(sessionSecret)) {
    errors.push("SESSION_SECRET must be non-default and at least 32 characters");
  }

  if (adminPassword.length < 12 || ["change-me", "fund-management-admin"].includes(adminPassword)) {
    errors.push("ADMIN_PASSWORD must be non-default and at least 12 characters");
  }

  if (postgresPassword.length < 12 || ["fundapp", "change-me", "change-me-postgres"].includes(postgresPassword)) {
    errors.push("POSTGRES_PASSWORD must be non-default and at least 12 characters");
  }

  for (const [name, value] of Object.entries({
    adminEmail,
    baseUrl,
    qwenApiKey,
    adminPassword,
    postgresPassword,
    sessionSecret,
    httpPort,
    sessionMaxAgeSeconds,
    postgresDb,
    postgresUser,
    qwenBaseUrl,
    qwenModel,
    releaseWriteMarker,
  })) {
    if (value && /[\r\n]/.test(value)) errors.push(`${name} cannot contain newlines`);
  }

  return errors;
}

function resolveSecureCookie(url) {
  if (hasFlag("--secure-cookie")) return true;
  if (hasFlag("--no-secure-cookie")) return false;
  return url.startsWith("https://");
}

function randomSecret(byteLength) {
  return randomBytes(byteLength).toString("base64url");
}

function quoteEnv(value) {
  return `"${String(value).replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
}

function resolveFromRoot(value) {
  return path.isAbsolute(value) ? value : path.resolve(repoRoot, value);
}

function hasFlag(flag) {
  return args.includes(flag);
}

function readOption(name) {
  const index = args.indexOf(name);
  if (index === -1) return undefined;
  return args[index + 1];
}

function printHelp() {
  console.log(`
Usage:
  npm run prepare:release-env -- --admin-email ops@example.com
  npm run prepare:release-env -- --admin-email ops@example.com --base-url https://fund.example.com
  npm run prepare:release-env -- --output .env.production --admin-email ops@example.com --force

Behavior:
  - Creates a gitignored env file for password-mode Compose deployment.
  - Generates SESSION_SECRET, ADMIN_PASSWORD, and POSTGRES_PASSWORD.
  - Requires a non-default administrator email.
  - Sets SESSION_COOKIE_SECURE=true automatically when --base-url starts with https://.
  - Does not print generated secrets.

Options:
  --output                    Env file to write. Defaults to .env.
  --force                     Overwrite an existing output file.
  --admin-email               Production administrator email. Required unless ADMIN_EMAIL is set.
  --admin-password            Explicit admin password. Defaults to a generated strong value.
  --session-secret            Explicit session secret. Defaults to a generated strong value.
  --postgres-password         Explicit PostgreSQL password. Defaults to a generated strong value.
  --base-url                  Public release URL. Also controls secure-cookie default.
  --secure-cookie             Force SESSION_COOKIE_SECURE=true.
  --no-secure-cookie          Force SESSION_COOKIE_SECURE=false.
  --qwen-api-key              Optional Qwen key. Defaults to QWEN_API_KEY or blank.
  --qwen-base-url             Qwen compatible-mode base URL.
  --qwen-model                Qwen model name.
  --write-marker              Stable release write marker. Defaults to RELEASE_WRITE_MARKER or a generated phase1 timestamp.
`);
}

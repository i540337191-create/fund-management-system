test('two distinct funds sum exact decimal cents and latest terms map once per fund', async (t) => {
    const f = await fixture(t), firstFundId = f.terms.allocations[0].fundId, secondFundId = 'test-second-fund';
    assert.notEqual(firstFundId, secondFundId);
    const terms = { ...f.terms, allocations:[{fundId:firstFundId,amount:'0.10'},{fundId:secondFundId,amount:'0.20'}] };
    await f.act({ action:'save_terms', terms, reason:'两只基金分摊三角钱' });
    assert.equal(f.d.terms[0].amount,'0.30');
    assert.deepEqual(f.d.terms[0].allocations,terms.allocations);
    const initial = structuredClone(f.d);
    await f.act({ action:'save_terms', terms:{...terms,allocations:[{fundId:firstFundId,amount:'0.10'},{fundId:firstFundId,amount:'0.20'}]}, reason:'拒绝重复基金' },f.admin,400);
    assert.deepEqual((await f.call('GET',f.url)).json().deals[0],initial);
    await f.act({ action:'save_terms', terms:{...terms,allocations:[{fundId:firstFundId,amount:'0.20'},{fundId:secondFundId,amount:'0.10'}]}, reason:'调整两基金分摊' });
    assert.equal(f.d.terms.length,2);
    assert.deepEqual(f.d.terms[0],initial.terms[0]);
    const latestTermsId = f.d.terms[1].id;
    for (const [fundId,expectedAmount] of [[firstFundId,'0.20'],[secondFundId,'0.10']]) {
        const response = await f.call('GET',`/api/funds/${fundId}/deals`);
        assert.equal(response.statusCode,200,response.body);
        const rows=response.json().allocations;
        assert.equal(rows.length,1);
        assert.equal(rows[0].dealId,f.d.id);
        assert.equal(rows[0].termsId,latestTermsId);
        assert.equal(rows[0].allocationAmount,expectedAmount);
        assert.equal(rows[0].amount,'0.30');
        assert.equal(rows[0].cashStatus,'not_recorded');
    }
    const projectDeals=(await f.call('GET',f.url)).json().deals;
    assert.equal(projectDeals.length,1);
    assert.deepEqual(projectDeals[0].terms[1].allocations,[{fundId:firstFundId,amount:'0.20'},{fundId:secondFundId,amount:'0.10'}]);
});

